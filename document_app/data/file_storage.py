import os
import uuid

from werkzeug.utils import secure_filename


class LocalFileStorage:
    """Stores original uploads outside the web templates/static folders."""

    def __init__(self, upload_folder):
        self.upload_folder = upload_folder
        os.makedirs(upload_folder, exist_ok=True)

    def save(self, file_storage, job_id):
        safe_name = secure_filename(file_storage.filename or "upload")
        extension = os.path.splitext(safe_name)[1].lower()
        stored_name = f"{job_id}{extension}"
        full_path = os.path.join(self.upload_folder, stored_name)
        file_storage.save(full_path)
        return stored_name, full_path

    def get_path(self, stored_name):
        # stored_name is generated by this service, but still normalize the path.
        safe_name = os.path.basename(stored_name)
        return os.path.join(self.upload_folder, safe_name)
